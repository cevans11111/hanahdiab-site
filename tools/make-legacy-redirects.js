#!/usr/bin/env node
// Writes functions/artwork.php.js and functions/news-detail.php.js so old links such as
//   /artwork.php?gallery=drawing&id=7   and   /news-detail.php?id=10
// land on the matching new page. Cloudflare's _redirects file cannot match query strings,
// so these two old addresses are handled by tiny Pages Functions instead.
//
// The old numeric ids never change, so this only needs re-running if content/*.md legacy_id
// values change. Run:  node tools/make-legacy-redirects.js
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const DIRS = { painting: "paintings", drawing: "drawings", sculpture: "sculptures" };

function front(file) {
  const m = fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n").match(/^---\n([\s\S]*?)\n---/);
  const o = {};
  for (const line of (m ? m[1] : "").split("\n")) {
    const k = line.match(/^([A-Za-z_]\w*):[ \t]*(.*)$/);
    if (k) o[k[1]] = k[2].trim().replace(/^["']|["']$/g, "");
  }
  return o;
}

const art = {}, news = {};
for (const f of fs.readdirSync(path.join(ROOT, "content/artwork")).filter((f) => f.endsWith(".md"))) {
  const d = front(path.join(ROOT, "content/artwork", f));
  if (d.legacy_id && DIRS[d.type]) art[d.legacy_id] = `/${DIRS[d.type]}/${f.replace(/\.md$/, "")}/`;
}
for (const f of fs.readdirSync(path.join(ROOT, "content/news")).filter((f) => f.endsWith(".md"))) {
  const d = front(path.join(ROOT, "content/news", f));
  if (d.legacy_id) news[d.legacy_id] = `/news/${f.replace(/\.md$/, "")}/`;
}

const fnDir = path.join(ROOT, "functions");
fs.mkdirSync(fnDir, { recursive: true });
for (const f of ["artwork.php.js", "news-detail.php.js"]) fs.rmSync(path.join(fnDir, f), { force: true });

fs.writeFileSync(path.join(fnDir, "_middleware.js"), `// Generated by tools/make-legacy-redirects.js. Handles the two old addresses that carry an ?id=:
//   /artwork.php?gallery=drawing&id=7  ->  /drawings/squeeze/
//   /news-detail.php?id=10             ->  /news/2009-12-26-.../
// public/_routes.json limits this function to just those two paths.
const ART = ${JSON.stringify(art, null, 1)};
const NEWS = ${JSON.stringify(news, null, 1)};
const GALLERY = { painting: "/paintings/", drawing: "/drawings/", sculpture: "/sculptures/" };

export function onRequest({ request, next }) {
  const url = new URL(request.url);
  const q = url.searchParams;
  let to = null;
  if (url.pathname === "/artwork.php") to = ART[q.get("id")] || GALLERY[q.get("gallery")] || "/paintings/";
  else if (url.pathname === "/news-detail.php") to = NEWS[q.get("id")] || "/news/";
  return to ? Response.redirect(new URL(to, url).toString(), 301) : next();
}
`);

fs.writeFileSync(path.join(ROOT, "public/_routes.json"), JSON.stringify({ version: 1, include: ["/artwork.php", "/news-detail.php"], exclude: [] }, null, 2) + "\n");

console.log(`Wrote functions/_middleware.js (${Object.keys(art).length} artworks, ${Object.keys(news).length} posts) and public/_routes.json`);
